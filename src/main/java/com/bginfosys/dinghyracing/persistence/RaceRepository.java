package com.bginfosys.dinghyracing.persistence;

import java.time.LocalDateTime;
import java.util.List;

import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.NativeQuery;
import org.springframework.data.repository.query.Param;
import org.springframework.format.annotation.DateTimeFormat;

import com.bginfosys.dinghyracing.model.Race;

public interface RaceRepository extends JpaRepository<Race, Long> {

	// _clazz field is normally generated by Hibernate to track the class to be created. 0 indicates parent class and 1 (or greater?) a subclass.
	// Attempting to guess value of _clazz for specific subclasses would unreliable, so this query does not support polymorphism. It is not possible to cast the returned Race to a it's appropriate subclass.
	// There is a possibility this query will break if Hibernate version changes due to use of an internal mechanism (_clazz) to map to entity type
	// If an instance of a subclass is required it should be obtained through a separate request rather than cast from a value returned from this query
	// It may be possible to resolve this by rewriting in JPQL if that is possible.
	// It might be better(?) to move this out of RaceRepository and build a DTO class that makes the purpose/ use and limitation clear?
	static String PLANNED_START_TIME_BETWEEN_QUERY = "SELECT id, fleet_id, name, last_lead_entry_id, last_lead_entry_laps_completed, duration, planned_laps, planned_start_time, start_time_offset, version, start_type, type, 0 as clazz_"
			+ " FROM (SELECT race.id, race.fleet_id, race.name, race.last_lead_entry_id, race.last_lead_entry_laps_completed, null AS duration, null AS planned_laps, race.version, MIN(planned_start_time.planned_start_time) AS planned_start_time"
			+ ", MIN(planned_start_time.start_time_offset) AS start_time_offset, MAX(planned_start_time.start_type) AS start_type, MAX(planned_start_time.type) AS type"
			+ " FROM dinghy_racing.race"
			+ "	LEFT JOIN (SELECT embedded_race_hosts.embedded_race_id AS id, planned_start_time AS planned_start_time, start_time_offset AS start_time_offset, start_type AS start_type, type AS type"
			+ "				FROM direct_race"
			+ "					LEFT JOIN embedded_race_hosts ON direct_race.id = embedded_race_hosts.hosts_id"
			+ "			) AS planned_start_time ON race.id = planned_start_time.id"
			+ "    LEFT JOIN embedded_race_hosts ON planned_start_time.id = embedded_race_hosts.hosts_id"
			+ " WHERE planned_start_time IS NOT NULL"
			+ " GROUP BY race.id, race.fleet_id, race.name, race.last_lead_entry_id, race.last_lead_entry_laps_completed, race.version"
			+ " UNION"
			+ " SELECT race.id, race.fleet_id, race.name, race.last_lead_entry_id, race.last_lead_entry_laps_completed, direct_race.duration, direct_race.planned_laps, race.version, direct_race.planned_start_time, direct_race.start_time_offset, direct_race.start_type, direct_race.type"
			+ " FROM race"
			+ "	LEFT JOIN direct_race ON race.id = direct_race.id"
			+ " WHERE planned_start_time IS NOT NULL) AS all_races"
			+ " WHERE planned_start_time >= :startTime AND planned_start_time <= :endTime;",
			countQuery = "SELECT COUNT(1)"
			+ " FROM (SELECT race.id, race.fleet_id, race.name, race.last_lead_entry_id, race.last_lead_entry_laps_completed, race.version, MIN(planned_start_time.planned_start_time) AS planned_start_time"
			+ ", MIN(planned_start_time.start_time_offset) AS start_time_offset"
			+ " FROM dinghy_racing.race"
			+ "	LEFT JOIN (SELECT embedded_race_hosts.embedded_race_id AS id, planned_start_time AS planned_start_time, start_time_offset AS start_time_offset"
			+ "				FROM direct_race"
			+ "					LEFT JOIN embedded_race_hosts ON direct_race.id = embedded_race_hosts.hosts_id"
			+ "			) AS planned_start_time ON race.id = planned_start_time.id"
			+ "    LEFT JOIN embedded_race_hosts ON planned_start_time.id = embedded_race_hosts.hosts_id"
			+ " WHERE planned_start_time IS NOT NULL"
			+ " GROUP BY race.id, race.fleet_id, race.name, race.last_lead_entry_id, race.last_lead_entry_laps_completed, race.version"
			+ " UNION"
			+ " SELECT race.id, race.fleet_id, race.name, race.last_lead_entry_id, race.last_lead_entry_laps_completed, race.version, direct_race.planned_start_time, direct_race.start_time_offset"
			+ " FROM race"
			+ "	LEFT JOIN direct_race ON race.id = direct_race.id"
			+ " WHERE planned_start_time IS NOT NULL) AS all_races"
			+ " WHERE planned_start_time >= :startTime AND planned_start_time <= :endTime;";
	
	// the result of this query does not support polymorphism (cannot cast instances of Race to subtypes)
	@NativeQuery(value = PLANNED_START_TIME_BETWEEN_QUERY)
	List<Race> findByPlannedStartTimeBetweenAsList(@Param("startTime") @DateTimeFormat(iso = DateTimeFormat.ISO.DATE_TIME) LocalDateTime startTime, 
			@Param("endTime") @DateTimeFormat(iso = DateTimeFormat.ISO.DATE_TIME) LocalDateTime endTime);

	// the result of this query does not support polymorphism (cannot cast instances of Race to subtypes)
	@NativeQuery(value = PLANNED_START_TIME_BETWEEN_QUERY)
	Page<Race> findByPlannedStartTimeBetween(@Param("startTime") @DateTimeFormat(iso = DateTimeFormat.ISO.DATE_TIME) LocalDateTime startTime, 
			@Param("endTime") @DateTimeFormat(iso = DateTimeFormat.ISO.DATE_TIME) LocalDateTime endTime, Pageable pageable);

}
